# 机制归因红线（ADR-0002 决策 4：只谈可动的任务条件，不给指标编造内部过程）
#
# 2026-11-20 真实模型实测两句"错结论"：
#   * 「这表明在回忆配对关系时，可能存在一定的混淆或回忆效率有待提升」
#     —— facts 里只有 hits/falseAlarms/meanRtMs，没有任何"混淆""回忆效率"的读数；
#   * 「有1次是符号类别错误（属于目标符号本身错误），2次是符号编码错误
#      （属于选项比对阶段失误）」—— 给 encWrong/catWrong **重新命名并编造认知机制**。
# 规则必须窄：**名词 + 归因动词同句共现**才判死，所以这三句正常话术必须放行：
#   「睡眠不足会拉低速度类表现」「间隔太短练习效应会让差值不好解释」
#   「虚报多说明有几题被熟悉感带偏了」（现有模板在用）。
# 知识块原文里的"作答依赖学习阶段的编码质量"也不在动词表里（"依赖"不是归因动词），
# 模型复述知识块不会被误杀。
# ---------------------------------------------------------------------------
